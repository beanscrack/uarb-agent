"""Capture the remaining demo evidence: modal opened, download click, portal,
receiver-side email (generated by agent_mail test, not sent), ZIP on disk."""
import shutil
import sys
sys.path.insert(0, ".")
from pathlib import Path

from playwright.sync_api import sync_playwright

import uarb_scrape as U

shots = Path("C:/Users/fortn/task1/uarb_agent/demo_src")
shots.mkdir(exist_ok=True)
n = [5]  # continue numbering from capture_demo


def snap(pg, tag):
    n[0] += 1
    p = shots / f"{n[0]:02d}_{tag}"
    pg.screenshot(path=str(p))
    print("shot", p, flush=True)


with sync_playwright() as p:
    b = p.chromium.launch(headless=False)
    pg = b.new_page(viewport={"width": 1440, "height": 900})
    pg.on("dialog", lambda d: d.accept())
    pg.goto(U.BASE, wait_until="domcontentloaded", timeout=90000)
    pg.wait_for_timeout(7000)
    U.type_text(pg, "#b0p0o254i0i0r1", "M12205")
    pg.locator("#b0p0o258i0i0r1").click()
    pg.wait_for_function("() => /Exhibits - \\d+/.test(document.body.innerText)", timeout=40000)
    snap(pg, "result2.png")
    U.open_tab(pg, "Exhibits", min_rows=6)
    snap(pg, "portal_exhibits.png")
    rows = U.visible_rows(pg)
    c = rows[0]
    pg.mouse.click(c["x"], c["y"])
    pg.wait_for_selector(".v-window:has-text('Download Files')", timeout=20000)
    snap(pg, "ready1.png")
    pg.locator(".v-window .fm-download-button:not(.v-disabled)").first.click()
    pg.wait_for_timeout(1200)
    snap(pg, "ready2.png")
    # exhibit rows down the page
    for _ in range(5):
        pg.keyboard.press("End")
        pg.wait_for_timeout(400)
    snap(pg, "end_page.png")
    # Key Documents tab: 6 docs
    pos = U.tab_pos(pg, "Key Documents")
    pg.mouse.click(pos["x"], pos["y"])
    pg.wait_for_function("() => /Found Count: \\d+/.test(document.body.innerText)", timeout=60000)
    pg.wait_for_timeout(1500)
    snap(pg, "keydocs.png")
    # Other Documents: 43
    pos = U.tab_pos(pg, "Other Documents")
    pg.mouse.click(pos["x"], pos["y"])
    pg.wait_for_function("() => /Found Count: \\d+/.test(document.body.innerText)", timeout=60000)
    pg.wait_for_timeout(2500)
    snap(pg, "otherdocs.png")
    b.close()
print("done")
